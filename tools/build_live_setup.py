#!/usr/bin/env python3
"""Build supabase/live_setup.sql: everything the live Supabase project still needs, in one file.

The live project already has the first six migrations (up to the compliance register). This joins the rest,
in order, followed by the demo data, so it can be pasted into the Supabase SQL Editor and run once.
Re-run this script whenever one of the files below changes:  python3 tools/build_live_setup.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PENDING = [
    "supabase/migrations/20261026110000_compliance_agent.sql",
    "supabase/migrations/20261028090000_staff_agent.sql",
    "supabase/migrations/20261029090000_audit_agent.sql",
    "supabase/migrations/20261030090000_integration.sql",
    "supabase/seed_demo.sql",
]

HEADER = """-- ============================================================================
-- beehive: live setup (generated by tools/build_live_setup.py, don't edit by hand)
--
-- Paste this whole file into Supabase -> SQL Editor -> New query, then click Run. It adds:
--   1. the compliance assistant (Gemini) tables and functions
--   2. the staff compliance agent
--   3. the audit-readiness agent
--   4. the integration that joins them into one system
--   5. the demo data (this RESETS the demo centre: Sara, Priya, Mia and all demo records)
--
-- It's safe to run again: every step checks what already exists, and the demo data is rebuilt each time.
-- The last row it returns is a new AI agent key. Paste it into Vercel -> Settings -> Environment Variables
-- as BEEHIVE_AGENT_KEY, then redeploy.
-- ============================================================================

-- Stop early, with a clear message, if the earlier migrations haven't been run on this project.
do $$
begin
  if to_regclass('public.compliance_requirements') is null or to_regclass('public.compliance_guides') is null
     or to_regclass('public.checklist_items') is null or to_regclass('public.agent_keys') is null then
    raise exception 'Run the first six files in supabase/migrations first (init up to compliance_register), then run this file again.';
  end if;
end $$;
"""

def main():
    parts = [HEADER]
    for rel in PENDING:
        sql = (ROOT / rel).read_text(encoding="utf-8").rstrip() + "\n"
        parts.append("\n-- ============================================================================\n-- " + rel +
                     "\n-- ============================================================================\n" + sql)
    out = ROOT / "supabase" / "live_setup.sql"
    out.write_text("".join(parts), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB) from {len(PENDING)} files")

if __name__ == "__main__":
    main()
